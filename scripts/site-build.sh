#!/bin/sh
#
# site-build.sh: generate the static site in site.out/ from site.in/.
#
# Feature: prompts/features/01-site-build.md
#
# Usage: site-build.sh [INPUT_DIR] [OUTPUT_DIR]
#
# The default INPUT_DIR is site.in/ and the default OUTPUT_DIR is site.out/,
# both relative to the repository root.
# Every site.in/*.txt input file is converted to site.out/<name>.html.
# The HTML page structure lives in site.in/template.html, not in this script.
# The template marker <!-- SITE-CONTENT --> marks where page content is inserted.
#
# Generated output is stamped with a generated-file marker and must not be
# edited manually.
set -eu

script_dir=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
repo_root=$(CDPATH= cd -- "$script_dir/.." && pwd)

input_dir=${1:-"$repo_root/site.in"}
output_dir=${2:-"$repo_root/site.out"}
template="$input_dir/template.html"
marker='<!-- SITE-CONTENT -->'

if [ ! -d "$input_dir" ]; then
    echo "site-build: input directory not found: $input_dir" >&2
    exit 1
fi

if [ ! -f "$template" ]; then
    echo "site-build: template not found: $template" >&2
    exit 1
fi

if ! grep -q "$marker" "$template"; then
    echo "site-build: template is missing the marker line: $marker" >&2
    exit 1
fi

mkdir -p "$output_dir"

built_count=0
for input_file in "$input_dir"/*.txt; do
    if [ ! -f "$input_file" ]; then
        continue
    fi
    base_name=$(basename "$input_file" .txt)
    escaped_title=$(printf '%s' "$base_name" | sed 's/\\/\\\\/g; s/&/\\&/g; s|/|\\/|g')
    output_file="$output_dir/$base_name.html"
    {
        echo '<!-- generated by scripts/site-build.sh; do not edit manually -->'
        sed "s/__TITLE__/$escaped_title/g" "$template" | sed "/$marker/q" | sed '$d'
        sed 's/^/    /' "$input_file"
        sed -n "/$marker/,\$p" "$template" | sed '1d'
    } > "$output_file"
    built_count=$((built_count + 1))
done

echo "site-build: built $built_count page(s) into $output_dir"
exit 0
